export const getLang = () => store.getLang();
export function setLang(l) { store.setLang(l); applyI18n(); }
export function applyI18n() {
  document.documentElement.lang = getLang();
  document.title = t('app.name');
  window.dispatchEvent(new CustomEvent('langchange', { detail: { lang: getLang() } }));
}
export function t(key, vars = {}, lang = getLang()) {
  const s = strings[lang]?.[key] ?? strings.cs[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
